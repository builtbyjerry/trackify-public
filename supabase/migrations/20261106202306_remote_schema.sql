CREATE OR REPLACE FUNCTION "public"."protect_pin_columns"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    AS $$
   begin
     if auth.role() <> 'service_role' and (
          new.pin_hash is distinct from old.pin_hash
       or new.pin_set_at is distinct from old.pin_set_at) then
       raise exception 'PIN columns can only be changed by the server';
     end if;
     return new;
   end $$;


ALTER FUNCTION "public"."protect_pin_columns"() OWNER TO "postgres";

